package com.wangzan101.mika.core.model

import com.wangzan101.mika.core.screen.observation.ReadTag
import kotlinx.serialization.Serializable
import kotlinx.serialization.Transient

@Serializable
sealed interface Part {
    @Serializable
    data class Text(val text: String) : Part
    /**
     * [width]/[height]: pixel size after encoding, 0 means unknown (only used to estimate tokens).
     * [screenshotId]: which screen read this image came from (view_past_screens can replay it); null when it is not a screen image (an image file that was read).
     */
    @Serializable data class Image(
        val pngBase64: String,
        val mime: String = "image/png",
        val width: Int = 0,
        val height: Int = 0,
        val screenshotId: Int? = null,
    ) : Part
    /**
     * [opaque]: adapter-private data that the SAME adapter must send back unchanged when this call is
     * replayed; other adapters ignore it.
     */
    @Serializable data class ToolCall(val id: String, val name: String, val argsJson: String, val opaque: String? = null) : Part
    /**
     * [reads]: the observations read from this result and recorded in the evidence ledger (id and shape); used only inside Claire (trimming decides how to shorten by the observation's shape and refers back to the id afterwards), never sent to the provider.
     */
    @Serializable data class ToolResult(val callId: String, val content: String, val isError: Boolean, val reads: List<ReadTag> = emptyList()) : Part
    /**
     * [opaque]: adapter-private like [ToolCall.opaque], records where this thinking came from (for example the URL and field it was received from on a compatible API);
     * on replay only the adapter that recognizes it uses it, other adapters ignore it. Null for old history and for thinking that need not be replayed.
     */
    @Serializable data class Thinking(val text: String, val opaque: String? = null) : Part
}

@Serializable
enum class Role { System, User, Assistant, Tool }

/** Who wrote the message: [User] is what the user said themselves (the task's own words, additions and photos mid-task), [Claire] is generated by Claire (notes, context, tool round trips). */
@Serializable
enum class Author { User, Mika }

/**
 * [author] is required (no default): if a newly added place puts in the user's words or photos, they will not be trimmed as a note from Claire.
 * Used only inside Claire (to keep the user's words during compaction), never sent to providers.
 * [uncached]: this message changes on every request (such as the freshly prepared background note) and may only go at the end; adapters put the moving cache mark
 * on the last block before these trailing messages so the next request still hits cache. Effective for this request only, never persisted.
 */
@Serializable
data class Message(
    val role: Role,
    val parts: List<Part>,
    val author: Author,
    @Transient val uncached: Boolean = false,
)

data class ToolSpec(val name: String, val description: String, val parametersJsonSchema: String)

enum class StopReason { EndTurn, ToolUse, MaxTokens, Other }

/**
 * [inputTokens] is the total input tokens (including cache hits, following the OpenAI prompt_tokens convention). [outputTokens] includes thinking;
 * [reasoningTokens] is the portion of thinking tokens the provider reports separately (0 when not reported separately, e.g. Anthropic).
 */
data class Usage(
    val inputTokens: Int, val outputTokens: Int, val cachedInputTokens: Int = 0, val reasoningTokens: Int = 0,
    /** A provider can explicitly report zero cache reads. An absent counter has no cache-rate denominator. */
    val cacheReported: Boolean = cachedInputTokens > 0,
)

data class ModelReply(val parts: List<Part>, val stopReason: StopReason, val usage: Usage?)
