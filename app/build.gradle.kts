// Build number on the About screen: the short hash of the current commit; "dev" when git is unavailable (e.g. building from a source package)
val gitHash: String = runCatching {
    providers.exec { commandLine("git", "rev-parse", "--short=7", "HEAD") }.standardOutput.asText.get().trim()
}.getOrNull()?.takeIf { it.isNotEmpty() } ?: "dev"

android {
    namespace = "com.wangzan101.mika"
    compileSdk = 36

    defaultConfig {
        // Claire installs alongside Mika (Kilv 2026-11-23): its own
        // applicationId, so both can live on one phone. The Kotlin
        // source package stays com.wangzan101.mika (class names only;
        // install identity is the applicationId). Provider authorities
        // use ${applicationId} and runtime code reads
        // context.packageName, so they follow automatically.
        applicationId = "com.kilv.claire"
        minSdk = 29
        targetSdk = 35
        versionCode = 63
        // Claire 2.1.1 — base: upstream Mika 0.1.51 (commit a85b8a7b).
        // Versioning (same scheme as Kai-custom): a.b.c; minor fix bumps c
        // (1.2.1, 1.3.1, 1.3.2), feature / major fix bumps b (1.3.0), rebase onto a new
        // upstream bumps a (2.0.0, b/c reset). versionCode increments each release.
        versionName = "2.1.1"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        buildConfigField("String", "GIT_HASH", "\"$gitHash\"")
        // Beta badge after the version number on the About screen; set to false for a stable release
        buildConfigField("boolean", "BETA", "false")
        buildConfigField("boolean", "ADB_LOGS", "false")
    }

    // The sandbox binary only has an arm64 build (jniLibs/arm64-v8a); the APK is not ABI-restricted, so
    // other devices still install it and show "this device does not support the sandbox".
    // The sandbox binary is executed straight from nativeLibraryDir, so it must be extracted to disk on install
    packaging { jniLibs { useLegacyPackaging = true } }

    // Published builds (perf, release) also get a per-architecture variant: besides the universal APK,
    // a smaller APK carrying only the arm64-v8a native libraries.
    // Both share code, resources, version number and signing and differ only in the other architectures
    // under lib/; each is a complete APK, not a split set installed together.
    // Outputs: app-universal-<type>.apk, app-arm64-v8a-<type>.apk. The split applies to every build type,
    // so it is enabled only when this build is meant to produce perf/release packages; building debug
    // alone still outputs app-debug.apk.
    splits {
        abi {
            isEnable = gradle.startParameter.taskNames.any { Regex("(?i)(perf|release)").containsMatchIn(it) }
            reset()
            include("arm64-v8a")
            isUniversalApk = true
        }
    }
    // The bundled runtime (assets/runtime/rootfs.tar.xz, generated by tools/sandbox/build-runtime.py) is already xz, so don't compress it again
    androidResources { noCompress += "xz" }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // Evaluation task set (repo-root eval/tasks) is packed into the test APK's assets; the on-device evaluation runner reads the tasks from there
    sourceSets.getByName("androidTest").assets.srcDir(rootProject.file("eval/tasks"))

    // Permanent release signing (Kilv 2026-11-23): 1.2.0 failed to install
    // over 1.1.0 because both were debug-signed and GitHub runners generate
    // a FRESH debug key on every run, so the signatures never matched. The
    // release key lives in GitHub Actions secrets (see
    // .github/workflows/release.yml) with a local backup under
    // ~/workspace/keystores/; it never enters the repo. Without the env
    // vars (local builds) this config stays empty and the release build
    // type keeps its default (debug) signing.
    signingConfigs {
        create("release") {
            val keystoreFile = System.getenv("KEYSTORE_FILE")
            if (keystoreFile != null) {
                storeFile = file(keystoreFile)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        // The published APK is the release build, signed with the
        // permanent key above when the CI secrets are present.
        getByName("release") {
            if (System.getenv("KEYSTORE_FILE") != null) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
        // Installs side by side during on-device acceptance testing, keeping the release build and user data; the default build identity is unchanged.
        if (providers.gradleProperty("devInstall").isPresent) getByName("debug") {
            applicationIdSuffix = ".dev"
            resValue("string", "app_name", "Mika Dev")
        }
        // Build for checking UI smoothness: like the release build it is not debuggable (debug builds skip
        // ahead-of-time compilation and the UI feels several times slower, so impressions don't count),
        // signed with the local debug key so it installs over the debug build and keeps its data; profiling tools can sample it. ./gradlew :app:assemblePerf
        create("perf") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            isProfileable = true
            matchingFallbacks += "release"
            // Comparing swipe feel on a real device also uses the optimized build, still installing over the .dev test build and keeping its data.
            if (providers.gradleProperty("devInstall").isPresent) {
                applicationIdSuffix = ".dev"
                resValue("string", "app_name", "Mika Dev")
            }
        }
        // Local log-inspection build: installs side by side, allows adb run-as, records detailed traces from the first launch.
        create("logs") {
            initWith(getByName("perf"))
            applicationIdSuffix = ".logs"
            versionNameSuffix = "-logs"
            isDebuggable = true
            isProfileable = false
            resValue("string", "app_name", "Mika Logs")
            buildConfigField("boolean", "ADB_LOGS", "true")
            matchingFallbacks += "release"
        }
    }

    buildFeatures {
        compose = true
        aidl = true
        buildConfig = true
    }
}

